export const obgynTransducers: string =
    "Ultrasound probes come in many different shapes and sizes. Some transducers are used on the skin of a woman's abdomen, while others are placed inside the vagina — a vaginal ultrasound is usually called a transvaginal ultrasound. Getting the transducer close to the cervix, uterus and ovaries allows for more detailed images to be created."

export const obgynHowItWorks: string =
    "During an OB-GYN ultrasound, the certified sonographer either moves a transducer along the skin or gently inserts a transvaginal transducer into the vagina. These transducers, or \"probes,\" emit sound waves beyond the range of human hearing. These harmless waves echo off internal organs, and a computer translates them into a visible image on a monitor."

